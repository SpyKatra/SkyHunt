-- Séries d'avions (737-800, 737-900ER, A321neo…) dans chaque famille (type), et bonus de nouvelle série.
--
-- Une capture peut préciser sa série (series_id = « famille.clé », ex. « b737-800.900er »). Règle de points
-- (même calcul que web/game.js, comparé par tests/leaderboard.js) :
--   + 2 pour la première capture d'une série, si la famille était déjà dans la flotte (pas cumulé avec le +5
--   d'un nouveau type). La série doit appartenir à la famille de la capture, sinon elle est ignorée.
-- Comme le type, la série fait partie de l'identification : modifiable après l'envoi.

create table public.aircraft_series (
  id      text primary key,
  type_id text not null references public.aircraft_types (id) on delete cascade
);
comment on table public.aircraft_series is 'Copie de web/fleet.js (tools/sql_catalogue.mjs) : séries de chaque type.';
alter table public.aircraft_series enable row level security;
create policy "séries : lecture" on public.aircraft_series for select to authenticated using (true);
revoke all on public.aircraft_series from anon;
grant select on public.aircraft_series to authenticated;

alter table public.captures add column series_id text check (series_id is null or length(series_id) <= 64);

