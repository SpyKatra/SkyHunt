// Familles d'avions (cartes SkyHunt) et leurs séries. Sans DOM : partagé avec l'app native.
//
// Famille = la carte : rareté, points, bonus de nouveau type (+5). Série = un modèle précis de la famille
// (737-800, 737-900ER…) : une nouvelle série d'une famille déjà capturée rapporte +2 (web/game.js).
// L'identifiant d'une série est « famille.clé » (ex. « b737-800.900er ») : NE JAMAIS changer un identifiant
// existant (il est stocké dans les captures et sur le serveur). Après un ajout :
//   node tools/sql_catalogue.mjs > supabase/migrations/<date>_catalogue.sql   (nouvelle migration)
//
// [id, nom, constructeur, catégorie, rareté, séries]
// Série : [clé, nom, règle] ; la règle (facultative) reconnaît le modèle exact donné par un registre
// (Transport Canada, FAA), en majuscules ; la première série dont la règle correspond l'emporte.

/** Séries « lettres » : letters('172', 'A B C') → 172, 172A, 172B, 172C (modèle exact, ex. « 172S »). */
function letters(base, list, { prefix = '', label = (s) => s } = {}) {
  const out = [[base.toLowerCase(), label(`${prefix}${base}`), new RegExp(`^${base}$`)]];
  for (const l of list.split(' ')) {
    out.push([`${base}${l}`.toLowerCase(), label(`${prefix}${base}${l}`), new RegExp(`^${base}${l}(\\b|[^A-Z])`)]);
  }
  return out;
}

